// exportPdf.js — Professional PDF report generator for AI Analysis charts.
// Uses jsPDF for layout and html2canvas to capture Recharts SVG charts.
import { jsPDF } from 'jspdf'
import html2canvas from 'html2canvas'
import { formatCurrency, formatPercentage, MONTHS_FULL } from './analytics'
import { robotoRegularBase64, robotoBoldBase64 } from './robotoFont'
import barangayLogoUrl from '../assets/brgy-logo-2.png'
import skLogoUrl from '../assets/logo.png'

// ── Constants ──────────────────────────────────────────────────────────────────
const PAGE_W = 210    // A4 width mm
const PAGE_H = 297    // A4 height mm
const MARGIN = 16     // print-safe but compact — leaves room to spare without wasting a page
const CONTENT_W = PAGE_W - MARGIN * 2
const FOOTER_Y = PAGE_H - 12
// How much space content must leave at the bottom of every page for the
// footer (rule + one or two text lines) to have clear room, never overlap.
const BOTTOM_RESERVE = 24

// One vertical rhythm for the whole report instead of a different hand-picked
// gap after every block. Every section, table, and strip closes on one of
// these, which is what keeps the spacing looking deliberate rather than
// accidental.
const SPACE = {
  xs: 2,    // a nudge between two blocks that belong to each other
  sm: 4,    // heading to the thing it labels
  md: 7,    // between blocks inside one section
  lg: 11,   // between sections
}

const COLORS = {
  brand:    [14, 107, 77],   // #0E6B4D
  dark:     [15, 31, 54],    // #0F1F36
  text:     [55, 65, 81],    // #374151
  muted:    [107, 114, 128], // #6B7280
  line:     [229, 231, 235], // #E5E7EB
  white:    [255, 255, 255],
  bgLight:  [249, 250, 251], // #F9FAFB
  danger:   [220, 107, 79],  // #DC6B4F
}

// ── Helpers ────────────────────────────────────────────────────────────────────

function initPdfDoc(orientation = 'portrait') {
  const doc = new jsPDF(orientation, 'mm', 'a4')
  doc.addFileToVFS('Roboto-Regular.ttf', robotoRegularBase64)
  doc.addFont('Roboto-Regular.ttf', 'Roboto', 'normal')
  doc.addFileToVFS('Roboto-Bold.ttf', robotoBoldBase64)
  doc.addFont('Roboto-Bold.ttf', 'Roboto', 'bold')
  doc.setFont('Roboto', 'normal')
  return doc
}

function setColor(doc, color) {
  doc.setTextColor(...color)
}

function drawLine(doc, y) {
  doc.setDrawColor(...COLORS.line)
  doc.setLineWidth(0.3)
  doc.line(MARGIN, y, PAGE_W - MARGIN, y)
}

function addFooter(doc, pageNum, totalPages, { confidentialityNote } = {}) {
  // The confidentiality note gets its own line above the main one — sharing
  // a baseline with the left-aligned system name was overlapping it, since
  // both are long enough to reach past the page's horizontal center.
  const ruleY = confidentialityNote ? FOOTER_Y - 9 : FOOTER_Y - 5

  // The footer is stamped onto finished pages, so it inherits whatever font
  // weight the body content last left set — it has to state its own.
  doc.setFont('Roboto', 'normal')

  doc.setDrawColor(...COLORS.line)
  doc.setLineWidth(0.3)
  doc.line(MARGIN, ruleY, PAGE_W - MARGIN, ruleY)

  if (confidentialityNote) {
    doc.setFontSize(6.5)
    setColor(doc, COLORS.muted)
    doc.text(confidentialityNote, PAGE_W / 2, FOOTER_Y - 4, { align: 'center' })
  }

  doc.setFontSize(8)
  setColor(doc, COLORS.muted)
  doc.text(`Page ${pageNum} of ${totalPages}`, PAGE_W - MARGIN, FOOTER_Y, { align: 'right' })
  doc.text('Generated by Cuenta — SK Budget Monitoring System', MARGIN, FOOTER_Y)
}

// A tight but safe bottom reserve — just enough for the footer and its rule,
// so a section keeps filling the page right up until it genuinely runs out
// of room instead of jumping to a fresh page early and leaving a gap behind.
//
// Exposes whether it actually broke, not just the resulting y — callers that
// need to redo per-page setup (a table redrawing its header row on the new
// page, say) can't tell a break happened from the y alone, since a page that
// was nearly full could coincidentally reset to close to the same value.
function pageBreakInfo(doc, y, needed = 30) {
  if (y + needed > PAGE_H - BOTTOM_RESERVE) {
    doc.addPage()
    return { y: MARGIN + 8, broke: true }
  }
  return { y, broke: false }
}

function checkPageBreak(doc, y, needed = 30) {
  return pageBreakInfo(doc, y, needed).y
}

// ── Chart capture ──────────────────────────────────────────────────────────────

async function captureChartImage(chartContainerEl) {
  if (!chartContainerEl) return null
  // Allocation exports opt into capturing their detailed HTML legend as well
  // as the Recharts SVG. Other reports keep capturing only the chart wrapper.
  const captureFull = chartContainerEl.dataset?.pdfCapture === 'full'
  const captureTarget = captureFull
    ? chartContainerEl
    : chartContainerEl.querySelector('.recharts-responsive-container') || chartContainerEl
  const requestedScale = Number(chartContainerEl.dataset?.pdfScale)
  const scale = Number.isFinite(requestedScale) && requestedScale >= 2 ? requestedScale : 2
  try {
    const canvas = await html2canvas(captureTarget, {
      backgroundColor: '#ffffff',
      scale,
      useCORS: true,
      logging: false,
    })
    return { dataUrl: canvas.toDataURL('image/png'), width: canvas.width, height: canvas.height }
  } catch (err) {
    console.warn('Chart capture failed:', err)
    return null
  }
}

// Fits a captured image inside a maxWidth x maxHeight box without distorting
// its aspect ratio (avoids squishing/cropping variable-height content like a
// pie chart + legend list).
function fitImageBox(image, maxWidth, maxHeight) {
  const naturalRatio = image.width / image.height
  let w = maxWidth
  let h = w / naturalRatio
  if (h > maxHeight) {
    h = maxHeight
    w = h * naturalRatio
  }
  return { w, h }
}

// ── Report Header ──────────────────────────────────────────────────────────────

function drawReportHeader(doc, { title, year, month, view = 'yearly', generatedAt, meta }) {
  let y = MARGIN

  // Brand bar
  doc.setFillColor(...COLORS.brand)
  doc.rect(0, 0, PAGE_W, 4, 'F')

  // System name
  y += 8
  doc.setFontSize(10)
  setColor(doc, COLORS.brand)
  doc.setFont('Roboto', 'bold')
  doc.text('CUENTA', MARGIN, y)
  doc.setFont('Roboto', 'normal')
  setColor(doc, COLORS.muted)
  doc.setFontSize(8)
  doc.text('SK Budget Monitoring and Documentation Tracking with AI Analysis', MARGIN, y + 5)

  // Report title
  y += 16
  doc.setFontSize(18)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(title, MARGIN, y)

  // Meta line
  y += 8
  doc.setFontSize(9)
  doc.setFont('Roboto', 'normal')
  setColor(doc, COLORS.muted)
  const selectedMonth = view === 'monthly' && month ? MONTHS_FULL[Number(month) - 1] : 'All months'
  const metaLine = meta || `Month: ${selectedMonth}  •  Year: ${year}  •  Generated: ${generatedAt}`
  doc.text(metaLine, MARGIN, y)

  y += 4
  drawLine(doc, y)

  return y + 8
}

// ── Official Letterhead Header ───────────────────────────────────────────────
// The government-style letterhead used by Cuenta's generated documents
// (Transmittal Letter, Purchase Request, etc.): the barangay seal and the SK
// logo flanking a centered Republic-of-the-Philippines text block. Reused
// here for the Expenses page's Export PDF report, at the barangay's request.

const imageDataUrlCache = new Map()

// jsPDF's addImage needs a base64 data URL (or an <img>/<canvas>), not the
// plain asset URL Vite gives an imported PNG — fetch it once per session and
// convert it, so a second export in the same tab skips the round trip.
async function loadImageAsDataUrl(url) {
  if (imageDataUrlCache.has(url)) return imageDataUrlCache.get(url)

  const promise = (async () => {
    const response = await fetch(url)
    const blob = await response.blob()
    return await new Promise((resolve, reject) => {
      const reader = new FileReader()
      reader.onload = () => resolve(reader.result)
      reader.onerror = () => reject(new Error('Could not read a letterhead logo image.'))
      reader.readAsDataURL(blob)
    })
  })()

  imageDataUrlCache.set(url, promise)
  return promise
}

async function drawOfficialLetterheadHeader(doc, { title, subtitle, meta }) {
  const centerX = PAGE_W / 2
  const logoSize = 18
  let y = MARGIN

  try {
    const [barangayLogo, skLogo] = await Promise.all([
      loadImageAsDataUrl(barangayLogoUrl),
      loadImageAsDataUrl(skLogoUrl),
    ])
    doc.addImage(barangayLogo, 'PNG', MARGIN, y, logoSize, logoSize)
    doc.addImage(skLogo, 'PNG', PAGE_W - MARGIN - logoSize, y, logoSize, logoSize)
  } catch (err) {
    // The report is still useful without the seals — never let a failed
    // image fetch block the export itself.
    console.warn('Could not embed the letterhead logos:', err)
  }

  let textY = y + 4
  setColor(doc, COLORS.dark)
  doc.setFontSize(8.5)
  doc.setFont('Roboto', 'normal')
  doc.text('Republic of the Philippines', centerX, textY, { align: 'center' })

  textY += 4.2
  doc.setFont('Roboto', 'bold')
  doc.text('REGION XII', centerX, textY, { align: 'center' })

  textY += 4.2
  doc.setFont('Roboto', 'normal')
  doc.text('Province of Cotabato', centerX, textY, { align: 'center' })

  textY += 4.2
  doc.text('Municipality of Midsayap', centerX, textY, { align: 'center' })

  textY += 4.2
  doc.setFont('Roboto', 'bold')
  doc.text('BARANGAY UPPER GLAD II', centerX, textY, { align: 'center' })

  // A step up in size marks this as the office issuing the report, not just
  // another line in the address, without needing a big gap to do it.
  textY += 6
  doc.setFontSize(10.5)
  doc.text('OFFICE OF THE SANGGUNIANG KABATAAN', centerX, textY, { align: 'center' })

  y = Math.max(textY, y + logoSize) + 8

  doc.setFontSize(13.5)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(title, centerX, y, { align: 'center' })
  y += 4

  // Names the period the report covers (e.g. the month) right under the
  // title, so it is the first thing read rather than a field further down.
  if (subtitle) {
    y += 2.5
    doc.setFontSize(11)
    doc.setFont('Roboto', 'bold')
    setColor(doc, COLORS.dark)
    doc.text(subtitle, centerX, y, { align: 'center' })
  }

  if (meta) {
    y += 4
    doc.setFontSize(8.5)
    doc.setFont('Roboto', 'normal')
    setColor(doc, COLORS.muted)
    doc.text(meta, centerX, y, { align: 'center' })
  }

  y += 5
  drawLine(doc, y)

  return y + 6
}

// ── Data Table ─────────────────────────────────────────────────────────────────

// `ruled` swaps the colored-header-bar/zebra-striped look for a clean
// horizontally-ruled table — a rule above and below the column headers,
// hairlines between rows, a closing rule at the bottom, and no vertical
// lines at all. The vertical lines are what made the expenses report read
// as a raw spreadsheet dump; without them the eye tracks each row straight
// across to its amount. Off by default so the other PDF exports built on
// this same table keep their existing look; the Expenses report opts in.
//
// `totalRow` ({ label, value, color }) renders one emphasised summary row
// inside the table's own frame — rule above, bold text, same column edges —
// instead of leaving a detached grey box floating underneath it.
function drawDataTable(doc, { columns, rows, startY, headerColor = COLORS.brand, ruled = false, totalRow = null }) {
  let y = startY
  const colWidths = columns.map((c) => c.width || Math.floor(CONTENT_W / columns.length))

  // Adjust last column to fill remaining width
  const usedWidth = colWidths.slice(0, -1).reduce((a, b) => a + b, 0)
  colWidths[colWidths.length - 1] = CONTENT_W - usedWidth

  // Ruled rows sit tighter than the boxed ones did: the old 8mm floor with
  // 2.6mm padding left every table looking stretched and half-empty, which
  // is most of what made a page of them feel messy.
  const cellPadX = ruled ? 3 : 4
  const cellPadY = ruled ? 2 : 2.6
  const lineHeight = ruled ? 3.9 : 4.1
  const minRowHeight = ruled ? 6.8 : 8
  const headerHeight = ruled ? 7.4 : 9

  // The three rule weights a ruled table uses, and nothing else: a dark
  // frame rule top and bottom, a mid rule under the headers and above the
  // total, and a hairline between data rows.
  function hRule(atY, weight) {
    const spec = {
      frame: [COLORS.dark, 0.35],
      mid: [COLORS.muted, 0.22],
      hair: [COLORS.line, 0.15],
    }[weight]
    doc.setDrawColor(...spec[0])
    doc.setLineWidth(spec[1])
    doc.line(MARGIN, atY, MARGIN + CONTENT_W, atY)
  }

  // Draws the header row at whatever y it's given and returns the y just
  // below it — called once up front, and again on every page a table's rows
  // spill onto, so a continuation page is still a recognizable table with a
  // header, not bare text.
  function renderHeader(atY) {
    const baseline = atY + headerHeight / 2 + 1.3
    let hx = MARGIN

    if (ruled) {
      // Small letter-spaced uppercase labels in muted grey: they read as
      // column captions rather than competing with the figures beneath.
      hRule(atY, 'frame')
      doc.setFontSize(7)
      doc.setFont('Roboto', 'bold')
      setColor(doc, COLORS.muted)
      columns.forEach((col, i) => {
        const right = col.align === 'right'
        const tx = right ? hx + colWidths[i] - cellPadX : hx + cellPadX
        doc.text(String(col.header).toUpperCase(), tx, baseline, right
          ? { align: 'right', charSpace: 0.25 }
          : { charSpace: 0.25 })
        hx += colWidths[i]
      })
      hRule(atY + headerHeight, 'mid')
    } else {
      // Header row — every header is centered over its column, regardless
      // of how that column's own values align, so the banner reads as one
      // clean row rather than following each column's data alignment.
      doc.setFillColor(...headerColor)
      doc.rect(MARGIN, atY, CONTENT_W, headerHeight, 'F')
      doc.setFontSize(8)
      doc.setFont('Roboto', 'bold')
      setColor(doc, COLORS.white)
      columns.forEach((col, i) => {
        doc.text(col.header, hx + colWidths[i] / 2, baseline, { align: 'center' })
        hx += colWidths[i]
      })
    }

    return atY + headerHeight
  }

  y = checkPageBreak(doc, y, headerHeight + 10)
  y = renderHeader(y)

  // Data rows — each cell's text is wrapped to its column width up front,
  // so a row can grow tall enough to fit its longest cell (usually
  // Description) instead of a fixed height that lets long text spill into
  // the row below it.
  //
  // The body face is re-stated on every row rather than once before the
  // loop: a row that spills onto a new page redraws the header, and the
  // header leaves the font bold — which was setting every row on every
  // continuation page in bold.
  rows.forEach((row, rowIndex) => {
    doc.setFont('Roboto', 'normal')
    doc.setFontSize(8)

    const cellLines = columns.map((col, i) => {
      const value = col.format ? col.format(row) : String(row[col.key] ?? '—')
      return doc.splitTextToSize(value, colWidths[i] - cellPadX * 2)
    })
    const maxLines = Math.max(1, ...cellLines.map((lines) => lines.length))
    const rowHeight = Math.max(minRowHeight, cellPadY * 2 + maxLines * lineHeight)

    const broken = pageBreakInfo(doc, y, rowHeight + 8)
    y = broken.y
    if (broken.broke && ruled) y = renderHeader(y)

    // Re-stated after the header, not just before the measuring above, since
    // rendering a continuation header leaves the font bold and small.
    doc.setFont('Roboto', 'normal')
    doc.setFontSize(8)

    if (ruled) {
      // A hairline above every row but the first — the header already has
      // its own rule, and doubling them there reads as a heavy border.
      if (rowIndex > 0 && !broken.broke) hRule(y, 'hair')
    } else if (rowIndex % 2 === 0) {
      doc.setFillColor(...COLORS.bgLight)
      doc.rect(MARGIN, y, CONTENT_W, rowHeight, 'F')
    }

    let x = MARGIN
    columns.forEach((col, i) => {
      const isNegative = col.highlightNegative && typeof row[col.key] === 'number' && row[col.key] < 0
      const customColor = col.colorFor ? col.colorFor(row) : null
      setColor(doc, isNegative ? COLORS.danger : (customColor || COLORS.text))

      const textX = col.align === 'right' ? x + colWidths[i] - cellPadX : x + cellPadX
      const textAlign = col.align === 'right' ? { align: 'right' } : {}
      let lineY = y + cellPadY + lineHeight - 1.3
      cellLines[i].forEach((line) => {
        doc.text(line, textX, lineY, textAlign)
        lineY += lineHeight
      })
      x += colWidths[i]
    })

    y += rowHeight
  })

  if (ruled && totalRow) {
    const rowHeight = minRowHeight + 1
    const broken = pageBreakInfo(doc, y, rowHeight + 8)
    y = broken.y
    if (broken.broke) y = renderHeader(y)

    hRule(y, 'mid')
    const baseline = y + rowHeight / 2 + 1.3
    doc.setFontSize(8)
    doc.setFont('Roboto', 'bold')
    setColor(doc, COLORS.dark)
    doc.text(totalRow.label, MARGIN + cellPadX, baseline)
    setColor(doc, totalRow.color || COLORS.dark)
    doc.text(String(totalRow.value), MARGIN + CONTENT_W - cellPadX, baseline, { align: 'right' })
    y += rowHeight
  }

  if (ruled) hRule(y, 'frame')

  return y + (ruled ? SPACE.md : 6)
}

// ── Summary Box ────────────────────────────────────────────────────────────────

function drawSummaryBox(doc, { title, items, startY }) {
  const rowH = 11
  const topPad = 9
  const bottomPad = 7
  const boxH = topPad + items.length * rowH + bottomPad

  // Section heading — kept with its box on the same page, and given its own
  // clear gap from whatever content came before it.
  let y = checkPageBreak(doc, startY, boxH + 18)
  doc.setFontSize(12)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(title, MARGIN, y)
  y += 8

  const boxTop = y
  doc.setFillColor(...COLORS.bgLight)
  doc.setDrawColor(...COLORS.line)
  doc.roundedRect(MARGIN, boxTop, CONTENT_W, boxH, 3, 3, 'FD')

  let rowY = boxTop + topPad
  items.forEach((item) => {
    doc.setFontSize(9)
    doc.setFont('Roboto', 'normal')
    setColor(doc, COLORS.muted)
    doc.text(item.label, MARGIN + 10, rowY)

    doc.setFont('Roboto', 'bold')
    setColor(doc, item.color || COLORS.dark)
    doc.text(item.value, MARGIN + CONTENT_W - 12, rowY, { align: 'right' })
    rowY += rowH
  })

  return boxTop + boxH + 12
}

// ── Graph Structure Box ────────────────────────────────────────────────────────

function drawGraphStructure(doc, { title, items, startY }) {
  let y = checkPageBreak(doc, startY, 10 + items.length * 7)

  doc.setFontSize(10)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(title, MARGIN, y)
  y += 6

  items.forEach((item) => {
    y = checkPageBreak(doc, y, 7)
    doc.setFontSize(8)
    doc.setFont('Roboto', 'bold')
    setColor(doc, COLORS.brand)
    doc.text('•', MARGIN + 4, y)
    doc.text(item.label + ':', MARGIN + 9, y)
    doc.setFont('Roboto', 'normal')
    setColor(doc, COLORS.text)
    doc.text(item.value, MARGIN + 9 + doc.getTextWidth(item.label + ':  '), y)
    y += 7
  })

  return y + 4
}

// ═══════════════════════════════════════════════════════════════════════════════
// PUBLIC: Export Budget vs Actual PDF
// ═══════════════════════════════════════════════════════════════════════════════

export async function exportBudgetVsActualPdf({ chartRef, bva, filters }) {
  const doc = initPdfDoc('portrait')
  const now = new Date()
  const generatedAt = now.toLocaleString()

  // ── Page 1: Header ──
  let y = drawReportHeader(doc, {
    title: 'Budget vs Actual Spending',
    year: filters.year,
    month: filters.month,
    view: filters.view,
    generatedAt,
  })

  // ── Chart Image ──
  const chartImg = await captureChartImage(chartRef)
  if (chartImg) {
    y = checkPageBreak(doc, y, 85)
    doc.setFontSize(10)
    doc.setFont('Roboto', 'bold')
    setColor(doc, COLORS.dark)
    doc.text('Approved Budget vs Actual Expenses', MARGIN, y)
    y += 4

    // Subtle border around chart
    doc.setDrawColor(...COLORS.line)
    doc.setLineWidth(0.3)
    doc.roundedRect(MARGIN, y, CONTENT_W, 72, 2, 2, 'S')
    doc.addImage(chartImg.dataUrl, 'PNG', MARGIN + 2, y + 2, CONTENT_W - 4, 68)
    y += 78
  }

  // ── Graph Structure ──
  y = drawGraphStructure(doc, {
    title: 'Graph Structure',
    startY: y,
    items: [
      { label: 'X-Axis', value: 'Months' },
      { label: 'Y-Axis', value: 'Amount (₱)' },
      { label: 'Series 1', value: 'Approved Budget' },
      { label: 'Series 2', value: 'Actual Expenses' },
    ],
  })

  // ── Data Table ──
  y = checkPageBreak(doc, y, 20)
  doc.setFontSize(11)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text('Budget vs Spending Data', MARGIN, y)
  y += 6

  const tableColumns = [
    { key: 'label', header: 'Month', width: 36 },
    { key: 'budget', header: 'Approved Budget', align: 'right', width: 38, format: (r) => formatCurrency(r.budget, { detailed: true }) },
    { key: 'spending', header: 'Actual Expenses', align: 'right', width: 38, format: (r) => formatCurrency(r.spending, { detailed: true }) },
    { key: 'variance', header: 'Remaining Budget', align: 'right', width: 36, format: (r) => formatCurrency(r.variance, { detailed: true }), highlightNegative: true },
    { key: 'percentUsed', header: 'Utilization', align: 'right', width: 26, format: (r) => formatPercentage(r.percentUsed, 2) },
  ]

  y = drawDataTable(doc, {
    columns: tableColumns,
    rows: bva.rowsWithData,
    startY: y,
  })

  // ── Budget Summary ──
  const totalBudget = bva.totalBudget
  const totalSpending = bva.totalSpending
  const totalVariance = bva.totalVariance
  const overallUtilization = totalBudget > 0 ? (totalSpending / totalBudget) * 100 : 0

  drawSummaryBox(doc, {
    title: 'Budget Summary',
    startY: y,
    items: [
      { label: 'Total Approved Budget', value: formatCurrency(totalBudget, { detailed: true }) },
      { label: 'Total Actual Expenses', value: formatCurrency(totalSpending, { detailed: true }) },
      { label: 'Total Remaining Budget', value: formatCurrency(totalVariance, { detailed: true }), color: totalVariance < 0 ? COLORS.danger : COLORS.brand },
      { label: 'Overall Utilization', value: formatPercentage(overallUtilization, 2) },
    ],
  })

  // ── Page numbers ──
  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    addFooter(doc, i, totalPages)
  }

  const periodSlug = filters.view === 'monthly' ? `${filters.year}-${String(filters.month).padStart(2, '0')}` : filters.year
  doc.save(`budget-vs-actual-${periodSlug}.pdf`)
}

