const REPORT_TYPE_LABELS = {
  monthly: 'Monthly',
  quarterly: 'Quarterly',
  yearly: 'Yearly',
}

// A restrained navy/gray/black/white palette for this report's own accents
// (rules, month bands, section headings) — kept separate from COLORS.brand,
// which other exports still use for their own header bars.
const EXPENSES_ACCENT = COLORS.dark

// Value text is clamped to the space its cell actually has, so a long
// category or status never runs under the figure sitting beside it.
function clampToWidth(doc, text, maxWidth) {
  const value = String(text ?? '—')
  if (doc.getTextWidth(value) <= maxWidth) return value
  let clipped = value
  while (clipped.length > 1 && doc.getTextWidth(`${clipped}…`) > maxWidth) {
    clipped = clipped.slice(0, -1)
  }
  return `${clipped.trim()}…`
}

// A compact two-column strip of label/value pairs, used wherever the report
// needs to state a handful of fields. It replaces the seven-row
// "Information | Value" tables that each ran a third of a page tall behind a
// header row that said nothing. `right` values are right-aligned to the page
// edge by default, which lines the money up into one clean column;
// `alignRightValues: false` keeps both halves reading as plain label/value
// pairs, which is what dates and counts want.
function drawInfoGrid(doc, { startY, left, right = [], alignRightValues = true }) {
  const rowCount = Math.max(left.length, right.length)
  if (!rowCount) return startY

  const halfW = CONTENT_W / 2
  const labelW = 34
  const padX = 3.5
  const rowH = 6.2
  const boxH = rowCount * rowH + 3

  const y = checkPageBreak(doc, startY, boxH + 6)

  doc.setFillColor(...COLORS.bgLight)
  doc.rect(MARGIN, y, CONTENT_W, boxH, 'F')
  doc.setDrawColor(...COLORS.line)
  doc.setLineWidth(0.15)
  doc.rect(MARGIN, y, CONTENT_W, boxH, 'S')

  let rowY = y + 1.5
  for (let i = 0; i < rowCount; i += 1) {
    const baseline = rowY + rowH / 2 + 1.2
    const pairs = [left[i], right[i]]

    pairs.forEach((pair, side) => {
      if (!pair) return
      const colX = MARGIN + side * halfW

      doc.setFontSize(7.4)
      doc.setFont('Roboto', 'normal')
      setColor(doc, COLORS.muted)
      doc.text(pair.label, colX + padX, baseline)

      doc.setFontSize(8)
      doc.setFont('Roboto', 'bold')
      setColor(doc, pair.color || COLORS.dark)

      const available = halfW - labelW - padX * 2
      const text = clampToWidth(doc, pair.value, available)
      if (side === 1 && alignRightValues) {
        doc.text(text, MARGIN + CONTENT_W - padX, baseline, { align: 'right' })
      } else {
        doc.text(text, colX + padX + labelW, baseline)
      }
    })

    rowY += rowH
  }

  return y + boxH + SPACE.md
}

// Top-level heading for one of the report's own sections. Title case and
// bold, one clear step above the small letter-spaced uppercase captions the
// tables use for their columns, so the two never compete.
//
// `followedBy` is the room whatever it introduces will itself insist on — a
// heading has no business fitting on a page its own section can't start on.
function drawSectionLabel(doc, { text, startY, followedBy = 0 }) {
  const y = checkPageBreak(doc, startY, SPACE.sm + 1 + Math.max(11, followedBy))
  doc.setFontSize(9.5)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(text, MARGIN, y)
  return y + SPACE.sm + 1
}

// A month's own banded heading, used to split Quarterly and Yearly reports
// into per-month sections. Not drawn for Monthly reports — a report already
// scoped to one month doesn't need a second heading announcing it.
//
// `followedBy` is however much room whatever comes next is itself going to
// insist on. Reserving the band alone was not enough: the band would fit at
// the foot of a page, and then the record under it would demand a fresh one,
// leaving the month name stranded above a blank half-page.
function drawMonthHeading(doc, { label, startY, recordCount, followedBy = 0 }) {
  const bandH = 8
  const y = checkPageBreak(doc, startY, bandH + SPACE.md + followedBy)

  doc.setFillColor(...COLORS.bgLight)
  doc.rect(MARGIN, y, CONTENT_W, bandH, 'F')
  doc.setDrawColor(...EXPENSES_ACCENT)
  doc.setLineWidth(0.35)
  doc.line(MARGIN, y, MARGIN + CONTENT_W, y)
  doc.line(MARGIN, y + bandH, MARGIN + CONTENT_W, y + bandH)

  const baseline = y + bandH / 2 + 1.5
  doc.setFontSize(9)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(String(label).toUpperCase(), MARGIN + 3.5, baseline, { charSpace: 0.35 })

  doc.setFontSize(7.4)
  doc.setFont('Roboto', 'normal')
  setColor(doc, COLORS.muted)
  const countLabel = recordCount === 1 ? '1 record' : `${recordCount} records`
  doc.text(countLabel, MARGIN + CONTENT_W - 3.5, baseline, { align: 'right' })

  return y + bandH + SPACE.md
}

// Anywhere the report has to say that something is empty — a month with no
// records, a record with no transactions — it says so inside the same light
// bordered box, at the width of the table that would otherwise be there, so
// the absence reads as stated rather than as a gap where a table failed to
// render. Yearly reports run a lot of these.
const EMPTY_NOTE_H = 9

function drawEmptyNote(doc, { startY, text }) {
  const boxH = EMPTY_NOTE_H
  const y = checkPageBreak(doc, startY, boxH + 6)

  doc.setDrawColor(...COLORS.line)
  doc.setLineWidth(0.15)
  doc.rect(MARGIN, y, CONTENT_W, boxH, 'S')
  doc.setFontSize(7.8)
  doc.setFont('Roboto', 'normal')
  setColor(doc, COLORS.muted)
  doc.text(text, PAGE_W / 2, y + boxH / 2 + 1.2, { align: 'center' })

  return y + boxH + SPACE.md
}

// A rough (slight under-)estimate of a record's section height, assuming
// none of its cells wrap to more than one line — enough to decide whether
// starting it fresh on the next page keeps it in one piece. Undercounting
// only means a record with a lot of wrapped text still splits naturally
// (handled correctly either way), never an infinite loop forcing new pages.
function estimateRecordSectionHeight(record) {
  const titleH = 6.5
  const summaryH = 4 * 6.2 + 3 + SPACE.md // the four-row summary strip
  const breakdownH = record.transactions.length
    ? 7.4 + record.transactions.length * 6.8 + 7.8 + SPACE.md // header + rows + total
    : 9 + SPACE.md
  return titleH + summaryH + breakdownH + SPACE.sm
}

// The smallest block of a record that has to stay together when the record
// does have to split across a page: its title, its summary strip, and the
// first line or two of its expense table. Splitting any tighter than this
// leaves an orphaned record name at the foot of a page.
const RECORD_MIN_BLOCK = 46

// Short records are worth pulling onto a fresh page whole; long ones are let
// flow, because forcing those to start fresh is what was leaving half-empty
// pages behind. This is the one place that decision is made, so the month
// heading above a record can reserve exactly what the record will demand.
function recordSpaceDemand(record) {
  const estimatedHeight = estimateRecordSectionHeight(record)
  const freshPageCapacity = PAGE_H - (MARGIN + 8) - BOTTOM_RESERVE
  return estimatedHeight <= freshPageCapacity * 0.55 ? estimatedHeight : RECORD_MIN_BLOCK
}

// One approved Project/Event/Payroll record: a title line, a compact
// two-column summary strip, then its expense transactions as a single ruled
// table closed by its own total row.
function drawRecordSection(doc, { record, startY }) {
  let y = checkPageBreak(doc, startY, recordSpaceDemand(record))

  // A title is drawn from its baseline while the strips and tables below it
  // are drawn from their top edge, so without this nudge the name sits a
  // couple of millimetres tighter under whatever precedes it than every
  // other block does, and reads as part of that heading.
  y += SPACE.xs

  // Title line: the record's name on the left, its type on the right, so the
  // eye finds names down one edge instead of reading past a parenthetical to
  // get to the next one.
  doc.setFontSize(7.4)
  doc.setFont('Roboto', 'normal')
  setColor(doc, COLORS.muted)
  const typeText = String(record.type).toUpperCase()
  const typeWidth = doc.getTextWidth(typeText) + 6
  doc.text(typeText, MARGIN + CONTENT_W, y, { align: 'right', charSpace: 0.3 })

  doc.setFontSize(10)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text(clampToWidth(doc, record.name, CONTENT_W - typeWidth), MARGIN, y)
  y += SPACE.sm

  y = drawInfoGrid(doc, {
    startY: y,
    left: [
      { label: 'Category', value: record.category },
      { label: 'Status', value: record.status },
      { label: 'Utilization', value: `${formatPercentage(record.utilization, 1)} — ${record.utilizationStatus}` },
    ],
    right: [
      { label: 'Approved Budget', value: formatCurrency(record.approvedBudget, { detailed: true }) },
      { label: 'Actual Expenses', value: formatCurrency(record.totalExpenses, { detailed: true }) },
      {
        label: 'Remaining Balance',
        value: formatCurrency(record.remainingBudget, { detailed: true }),
        color: record.remainingBudget < 0 ? COLORS.danger : COLORS.dark,
      },
      {
        label: 'Returned Budget',
        value: record.returnedBudget > 0 ? formatCurrency(record.returnedBudget, { detailed: true }) : 'None',
      },
    ],
  })

  if (record.transactions.length) {
    y = drawDataTable(doc, {
      startY: y,
      ruled: true,
      columns: [
        { key: 'dateLabel', header: 'Date', width: 26 },
        { key: 'description', header: 'Particulars', width: CONTENT_W - 26 - 40 },
        { key: 'amount', header: 'Amount', align: 'right', width: 40, format: (r) => formatCurrency(r.amount, { detailed: true }) },
      ],
      rows: record.transactions,
      totalRow: {
        label: 'Total Expenses',
        value: formatCurrency(record.totalExpenses, { detailed: true }),
      },
    })
  } else {
    y = drawEmptyNote(doc, { startY: y, text: 'No expense transactions recorded for this record.' })
  }

  return y + SPACE.sm
}

// The height of the month band (when one is drawn) plus whatever the first
// thing under it will demand — what the Expense Breakdown heading has to
// have available before it is worth drawing at all.
const MONTH_BAND_H = 8

function monthBlockDemand(monthData, reportType) {
  const under = monthData.records.length
    ? recordSpaceDemand(monthData.records[0])
    : EMPTY_NOTE_H
  return reportType === 'monthly' ? under : MONTH_BAND_H + SPACE.md + under
}

// The report-level amounts table — used for both the opening Overall
// Financial Summary and the closing Report Totals so the two read as the
// same kind of statement rather than two differently-shaped ones.
function amountsTableHeight(rowCount) {
  return 7.4 + rowCount * 6.8 + 7.8 // header + rows + total row
}

function drawAmountsTable(doc, { startY, rows, totalRow }) {
  return drawDataTable(doc, {
    startY,
    ruled: true,
    columns: [
      { key: 'label', header: 'Particulars', width: CONTENT_W - 50 },
      { key: 'value', header: 'Amount', align: 'right', width: 50, colorFor: (row) => row.color || COLORS.dark },
    ],
    rows,
    totalRow,
  })
}

