// PUBLIC: Export Monthly Spending Trend PDF
// ═══════════════════════════════════════════════════════════════════════════════

export async function exportMonthlySpendingPdf({ chartRef, tableRows, filters }) {
  const doc = initPdfDoc('portrait')
  const now = new Date()
  const generatedAt = now.toLocaleString()

  // ── Page 1: Header ──
  let y = drawReportHeader(doc, {
    title: 'Monthly Spending Trend',
    year: filters.year,
    month: filters.month,
    view: filters.view,
    generatedAt,
  })

  // ── Chart Image ──
  const chartImg = await captureChartImage(chartRef)
  if (chartImg) {
    y = checkPageBreak(doc, y, 85)
    doc.setFontSize(10)
    doc.setFont('Roboto', 'bold')
    setColor(doc, COLORS.dark)
    doc.text(`Monthly Spending — ${filters.year}`, MARGIN, y)
    y += 4

    doc.setDrawColor(...COLORS.line)
    doc.setLineWidth(0.3)
    doc.roundedRect(MARGIN, y, CONTENT_W, 72, 2, 2, 'S')
    doc.addImage(chartImg, 'PNG', MARGIN + 2, y + 2, CONTENT_W - 4, 68)
    y += 78
  }

  // ── Graph Structure ──
  y = drawGraphStructure(doc, {
    title: 'Graph Structure',
    startY: y,
    items: [
      { label: 'X-Axis', value: 'Months' },
      { label: 'Y-Axis', value: 'Spending Amount (₱)' },
      { label: 'Series', value: 'Actual Monthly Spending' },
    ],
  })

  // ── Data Table ──
  y = checkPageBreak(doc, y, 20)
  doc.setFontSize(11)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text('Monthly Spending Data', MARGIN, y)
  y += 6

  // Build change from previous month
  const dataWithChange = tableRows.map((r, i) => {
    const prev = i > 0 ? tableRows[i - 1].total : null
    const change = prev != null ? r.total - prev : null
    let trendDir = '—'
    if (change !== null) {
      trendDir = change > 0 ? 'Increasing' : change < 0 ? 'Decreasing' : 'Stable'
    }
    return { ...r, changeAmount: change, trendDirection: trendDir }
  })

  const tableColumns = [
    { key: 'monthFull', header: 'Month', width: 30 },
    { key: 'total', header: 'Total Spending', align: 'right', width: 36, format: (r) => formatCurrency(r.total, { detailed: true }) },
    { key: 'changeAmount', header: 'Change', align: 'right', width: 36, format: (r) => r.changeAmount !== null ? (r.changeAmount > 0 ? '+' : '') + formatCurrency(r.changeAmount, { detailed: true }) : '—', highlightNegative: false },
    { key: 'trendDirection', header: 'Trend', width: 24 },
    { key: 'count', header: 'Approved', align: 'right', width: 20, format: (r) => String(r.count) },
    { key: 'missing', header: 'Missing Receipts', align: 'right', width: 28, format: (r) => String(r.missing) },
  ]

  y = drawDataTable(doc, {
    columns: tableColumns,
    rows: dataWithChange,
    startY: y,
  })

  // ── Spending Summary ──
  const totalSpending = tableRows.reduce((a, r) => a + r.total, 0)
  const nonZeroRows = tableRows.filter((r) => r.total > 0)
  const highest = nonZeroRows.reduce((max, r) => (r.total > (max?.total || 0) ? r : max), null)
  const lowest = nonZeroRows.reduce((min, r) => (r.total < (min?.total || Infinity) ? r : min), null)
  const average = nonZeroRows.length ? totalSpending / nonZeroRows.length : 0

  drawSummaryBox(doc, {
    title: 'Spending Summary',
    startY: y,
    items: [
      { label: 'Total Spending', value: formatCurrency(totalSpending, { detailed: true }) },
      { label: 'Highest Spending Month', value: highest ? `${highest.monthFull} (${formatCurrency(highest.total, { detailed: true })})` : '—' },
      { label: 'Lowest Spending Month', value: lowest ? `${lowest.monthFull} (${formatCurrency(lowest.total, { detailed: true })})` : '—' },
      { label: 'Average Monthly Spending', value: formatCurrency(average, { detailed: true }) },
    ],
  })

  // ── Page numbers ──
  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    addFooter(doc, i, totalPages)
  }

  doc.save(`monthly-spending-trend-${filters.year}.pdf`)
}

// PUBLIC: Export category allocation / spending-distribution PDF.
export async function exportBudgetAllocationPdf({ chartRef, categories, filters }) {
  const doc = initPdfDoc('portrait')
  const generatedAt = new Date().toLocaleString()
  const rows = (categories || []).filter((row) => Number(row.value) > 0)
  const total = rows.reduce((sum, row) => sum + Number(row.value || 0), 0)
  const totalRecords = rows.reduce((sum, row) => sum + Number(row.count || 0), 0)

  let y = drawReportHeader(doc, {
    title: 'Actual Expenses by Category',
    year: filters.year,
    month: filters.month,
    view: filters.view,
    generatedAt,
  })

  const chartImg = await captureChartImage(chartRef)
  if (chartImg) {
    y = checkPageBreak(doc, y, 91)
    doc.setFontSize(10)
    doc.setFont('Roboto', 'bold')
    setColor(doc, COLORS.dark)
    doc.text('Recorded Expense Distribution', MARGIN, y)
    y += 5

    doc.setDrawColor(...COLORS.line)
    doc.setLineWidth(0.3)
    doc.roundedRect(MARGIN, y, CONTENT_W, 78, 2, 2, 'S')
    doc.addImage(chartImg, 'PNG', MARGIN + 2, y + 2, CONTENT_W - 4, 74)
    y += 84
  }

  y = checkPageBreak(doc, y, 20)
  doc.setFontSize(11)
  doc.setFont('Roboto', 'bold')
  setColor(doc, COLORS.dark)
  doc.text('Expense Table', MARGIN, y)
  y += 6

  y = drawDataTable(doc, {
    startY: y,
    columns: [
      { key: 'name', header: 'Category', width: 57 },
      { key: 'count', header: 'Records', align: 'right', width: 25 },
      { key: 'value', header: 'Actual Expenses', align: 'right', width: 54, format: (row) => formatCurrency(row.value, { detailed: true }) },
      { key: 'percent', header: 'Share', align: 'right', width: 38, format: (row) => formatPercentage(row.percent, 2) },
    ],
    rows,
  })

  const largest = rows[0] || null
  drawSummaryBox(doc, {
    title: 'Financial Summary',
    startY: y,
    items: [
      { label: 'Total Actual Expenses', value: formatCurrency(total, { detailed: true }) },
      { label: 'Expense Records', value: String(totalRecords) },
      { label: 'Categories Represented', value: String(rows.length) },
      { label: 'Largest Category', value: largest ? largest.name : '—' },
      { label: 'Largest Category Share', value: largest ? formatPercentage(largest.percent, 2) : '0.00%' },
    ],
  })

  const totalPages = doc.internal.getNumberOfPages()
  for (let page = 1; page <= totalPages; page += 1) {
    doc.setPage(page)
    addFooter(doc, page, totalPages)
  }

  const periodSlug = filters.view === 'monthly' ? `${filters.year}-${String(filters.month).padStart(2, '0')}` : filters.year
  doc.save(`budget-allocation-${periodSlug}.pdf`)
}

